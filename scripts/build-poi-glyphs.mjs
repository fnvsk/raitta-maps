const num = (value) => Number(value ?? 0);

function toPath([tag, attrs]) {
  switch (tag) {
    case 'path':
      return attrs.d;
    case 'circle': {
      const [cx, cy, r] = [num(attrs.cx), num(attrs.cy), num(attrs.r)];
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;
    }
    case 'ellipse': {
      const [cx, cy, rx, ry] = [num(attrs.cx), num(attrs.cy), num(attrs.rx), num(attrs.ry)];
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`;
    }
    case 'rect': {
      const [x, y, w, h] = [num(attrs.x), num(attrs.y), num(attrs.width), num(attrs.height)];
      const r = Math.min(num(attrs.rx ?? attrs.ry), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}z`;
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}z`;
    }
    case 'line':
      return `M${num(attrs.x1)} ${num(attrs.y1)}L${num(attrs.x2)} ${num(attrs.y2)}`;
    case 'polyline':
    case 'polygon': {
      const points = attrs.points.trim().split(/[\s,]+/).map(Number);
      let d = `M${points[0]} ${points[1]}`;
      for (let i = 2; i < points.length; i += 2) d += `L${points[i]} ${points[i + 1]}`;
      return tag === 'polygon' ? `${d}z` : d;
    }
    default:
      throw new Error(`Unknown element ${tag}`);
  }
}

